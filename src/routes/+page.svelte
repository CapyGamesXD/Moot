<script>
	//@ts-nocheck

	let displayText = $state('');

	let rows = $state([
		[{ number: 1 }, { number: 2 }, { number: 3 }],
		[{ number: 4 }, { number: 5 }, { number: 6 }],
		[{ number: 7 }, { number: 8 }, { number: 9 }]
	]);
	const possibleResponses = [
		'Contacting the mainframe...',
		'Parsing responses...',
		'Balancing weights...',
		'Multiplying matrices...',
		'Thinking really hard...',
		'Processing...',
		'Hmmm...',
		'Fetching...',
		'This is a tough one...',
		'Retreiving database...',
		'Checking security...',
		'Toasting bread...',
		'Wasting water...'
	];
	let volatileDisplayBooleanHeyWaitThisCanBeMyEasterEggVariableForThisProject = false;
	let page = $state(1);
	async function calculate() {
		const toPredict = displayText
			.split('+')
			.map(Number)
			.map((n) => n / 100);
		if (toPredict.length > 2) {
			alert('Calculation exceeds length limit. Please format as X + Y, not X + Y + Z :)');
			displayText = '';
		} else {
			if (toPredict.length == 2) {
				displayText = 'Calculating...';
				let messageCount = $state(0);
				setInterval(() => {
					if (messageCount < 4) {
						const random = Math.floor(Math.random() * possibleResponses.length);
						displayText = possibleResponses[random];
						messageCount++;
					}
				}, 1000);

				setTimeout(async () => {
					const response = await fetch('/api/predict', {
						method: 'POST',
						headers: { 'Content-Type': 'application/json' },
						body: JSON.stringify({ toPredict })
					});

					const reply = await response.json();
					displayText = Math.round(reply.output * 100);
					volatileDisplayBooleanHeyWaitThisCanBeMyEasterEggVariableForThisProject = true;
				}, 5000);
			}

			if (toPredict.length == 1) {
				displayText = 'Thinking really hard... This is a hard one...';
				volatileDisplayBooleanHeyWaitThisCanBeMyEasterEggVariableForThisProject = true;
				setTimeout(() => {
					displayText = (toPredict[0] * 100).toString();
				}, 2500);
			}
		}
	}

	function addNum(item) {
		if (
			(item === '+' && displayText[displayText.length - 1] === '+') ||
			(!displayText[0] && item === '+')
		) {
			alert('Input character is invalid.');
		} else {
			if (volatileDisplayBooleanHeyWaitThisCanBeMyEasterEggVariableForThisProject) {
				displayText = '';
				displayText += item;
				volatileDisplayBooleanHeyWaitThisCanBeMyEasterEggVariableForThisProject = false;
			} else {
				displayText += item;
			}
		}
	}
</script>

<div class="centerDiv">
	<h1 style="margin-bottom: 30px;">Moot</h1>
	{#if page === 1}
		<p>
			Welcome to Moot! <br /> We're putting AI into everything these days, right? Why not your
			calculator too? 🫪 (Just to clarify, this is a joke :D) <br /> Moot is trained on 80,000
			arithmetic examples (generated by yours truly on <a href="/generateDataset">this</a> page) to
			guess the correct answer. <br /> <br /> What are the benefits of this method? <br /> It's
			funnier, I guess! <br /> This is kinda the sequel to my project "ragebait calculator". It's made
			to be impractical and somewhat annoying, hence the blinding colour scheme and horrible interface
			XD
		</p>
		<button style="margin-top: 20px;" class="okButton" onclick={() => (page = 2)}>Continue</button>
	{:else if page === 2}
		<div class="calculator">
			<div style="margin-bottom: 10px;" class="screen">
				<p class="pixelly">{displayText}</p>
			</div>
			{#each rows as row}
				<div class="row">
					{#each row as item}
						<button onclick={() => addNum(item.number)} class="calcButton">{item.number}</button>
					{/each}
				</div>
			{/each}
			<div class="row">
				<button class="commandButton" onclick={() => addNum('+')}>+</button>
				<button class="calcButton" onclick={() => addNum(0)}>0</button>
				<button class="commandButton" onclick={() => calculate()}>=</button>
			</div>
		</div>
	{/if}
</div>

